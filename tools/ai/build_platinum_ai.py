"""Generate the reviewable AI instruction stream from a local pokeplatinum checkout.
Usage: python3 tools/ai/build_platinum_ai.py /path/to/pokeplatinum
No ROM, build products, or network access are required.
"""
import csv, hashlib, json, pathlib, re, subprocess, sys
src = pathlib.Path(sys.argv[1]).resolve()
out = pathlib.Path(__file__).resolve().parents[2] / 'js/calc_ui/move_ai_preview/platinum_ai_script.js'
constants = {'TRUE': 1, 'FALSE': 0, 'TABLE_END': 0xffffffff}
for p in sorted((src / 'generated').glob('*.txt')):
    # Only simple enumerations; flag expressions are supplied by headers below.
    lines = p.read_text().splitlines()
    for i, line in enumerate(lines):
        if re.fullmatch(r'[A-Z][A-Z_0-9]*', line): constants[line] = i
raw = {}
for p in sorted((src / 'include/constants').rglob('*.h')):
    s = re.sub(r'/\*.*?\*/', '', p.read_text(), flags=re.S).replace('\\\n', '')
    for name, expr in re.findall(r'^#define\s+(\w+)\s+([^\n]+)', s, flags=re.M):
        raw[name] = expr.split('//')[0].strip()
used = set()
def value(expr, stack=()):
    expr = expr.strip()
    def replace(m):
        name=m.group()
        if name in stack: raise ValueError(('recursive',name))
        if name in raw: return str(value(raw[name], stack+(name,)))
        if name in constants: return str(constants[name])
        raise ValueError(('unknown',name,expr))
    expanded = re.sub(r'\b[A-Za-z_]\w*\b', replace, re.sub(r'(?<=\d)[uUlL]+\b', '', expr))
    if not re.fullmatch(r'[0-9xa-fA-F\s()+~|&<>*/%^-]+', expanded): raise ValueError(expr)
    return int(eval(expanded, {'__builtins__': {}}, {}))
s = (src/'asm/trainer_ai/trainer_ai_script.s').read_text()
labels={}; code=[]; tables={}; flags=[]; current=''
for lineNo, line in enumerate(s.splitlines(), 1):
    line=line.split(';')[0].strip()
    if not line or line.startswith(('.', '#')): continue
    if line.endswith(':'):
        current=line[:-1]; labels[current]=len(code); continue
    op, *tail = line.split(None,1)
    args=[a.strip() for a in tail[0].split(',')] if tail else []
    if op=='LabelDistance': flags.append(args[0]); continue
    if op=='TableEntry': tables.setdefault(current,[]).append(value(args[0])); continue
    code.append([op,args,current,lineNo])
for ins in code:
    ins[1]=[a if a in labels else value(a) for a in ins[1]]
# Keep the named constants used by the VM plus source IDs for moves/items/abilities.
for name in set(re.findall(r'\b[A-Z][A-Z_0-9]+\b',s)):
    try: used.add(name); constants[name]=value(name)
    except ValueError: used.discard(name)
for name in raw:
    if name.startswith(('MON_CONDITION_', 'VOLATILE_CONDITION_', 'MOVE_EFFECT_', 'SIDE_CONDITION_', 'FIELD_CONDITION_', 'TYPE_MULTI_','BATTLE_TYPE_')):
        try: constants[name]=value(name); used.add(name)
        except (ValueError, SyntaxError): pass
moves={}
for p in sorted((src/'res/battle/moves').glob('*/data.json')):
    d=json.loads(p.read_text()); token='MOVE_NONE' if p.parent.name == '0000' else 'MOVE_'+p.parent.name.upper()
    if token not in constants: continue
    moves[str(constants[token])]={'name':p.parent.name, 'power':d['power'], 'type':constants[d['type']], 'effect':constants[d['effect']['type']], 'category':d['class']}
items={}
for row in csv.DictReader((src/'res/items/pl_item_data.csv').open()):
    token=row['name'] if 'name' in row else list(row.values())[0]
    items[token]={k:row[k] for k in ['holdEffect','holdEffectParam','flingPower','naturalGiftPower','naturalGiftType']}
# Raw item rows retain the source token and item data fields, indexed below by token.
for name in list(constants):
    if name.startswith(('ABILITY_','MOVE_','ITEM_','TYPE_','BATTLE_STAT_','LOAD_','AI_WEATHER_','GENDER_','HOLD_EFFECT_')): used.add(name)
csource=(src/'src/battle/trainer_ai/trainer_ai.c').read_text()
def effect_list(name):
    body=re.search(r'static const u16 '+name+r'\[\] = \{(.*?)\};', csource,re.S).group(1)
    return [value(x) for x in re.findall(r'BATTLE_EFFECT_\w+',body)]
data={'sourceCommit':subprocess.check_output(['git','-C',str(src),'rev-parse','HEAD'],text=True).strip(), 'sourceSha256':hashlib.sha256(s.encode()).hexdigest(),'flags':flags, 'labels':labels, 'tables':tables,'code':code,'constants':{k:constants[k] for k in sorted(used)},'moves':moves,'items':items,'riskyEffects':effect_list('sRiskyMoves'),'altPowerEffects':effect_list('sAltPowerCalcMoves')}
out.write_text('// Generated by tools/ai/build_platinum_ai.py; edit the generator, not this file.\n// Source: pret/pokeplatinum asm/trainer_ai/trainer_ai_script.s and trainer_ai.c.\n(function(root) {\n    var data = '+('{\n' + ',\n'.join(json.dumps(k)+': '+ ('[\n' + ',\n'.join(json.dumps(row,ensure_ascii=False) for row in v) + '\n]' if k=='code' else json.dumps(v,ensure_ascii=False)) for k,v in data.items()) + '\n}')+';\n    root.PlatinumAiScript = data;\n    if (typeof module !== "undefined" && module.exports) module.exports = data;\n})(typeof window !== "undefined" ? window : globalThis);\n')
print(f'{len(code)} instructions, {len(tables)} tables, {len(moves)} moves -> {out}')
