import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Pin the upstream revision so blank dev defaults can be reproduced and reviewed.
const revision = process.argv[2] || '0e00adc6e131c6a32502f1bb23f50817727fc73e';
if (!/^[a-f0-9]{40}$/.test(revision)) throw new Error('Pass a full upstream commit SHA.');
const root = `https://raw.githubusercontent.com/smogon/damage-calc/${revision}`;
async function readSource(path) {
  const response = await fetch(`${root}/${path}`);
  if (!response.ok) throw new Error(`Failed to fetch ${path}: ${response.status}`);
  return response.text();
}
const [species, moves, license] = await Promise.all([
  readSource('calc/src/data/species.ts'),
  readSource('calc/src/data/moves.ts'),
  readSource('LICENSE'),
]);

function dataDeclarations(source, field) {
  const start = source.indexOf('const RBY:');
  const end = source.indexOf('const CHAMPIONS_LIST');
  if (start < 0 || end < start) throw new Error(`Unexpected upstream ${field} format.`);
  // The data declarations are JavaScript object literals with top-level TS annotations.
  const declarations = source.slice(start, end)
    .replace(/^(const\s+\w+):[^=\n]+=/gm, '$1 =')
    .replace(/\.baseSpecies!\]/g, '.baseSpecies]');
  const helper = field === 'species' ? 'function removeAttr(set, pokemon, attr) { delete set[pokemon][attr]; }\n' : '';
  const normalize = field === 'species' ? `\ntables.forEach(function (species, generation) {\n  if (generation >= 2) Object.values(species).forEach(function (pokemon) { delete pokemon.bs.sl; });\n});` : '';
  const body = `${helper}${declarations}\nconst tables = [{}, RBY, GSC, ADV, DPP, BW, XY, SM, SS, SV];${normalize}\nreturn tables;`;
  // Check the stripped declarations are valid JavaScript before saving them.
  new Function('extend', body);
  return `    ${field}: (function () {\n${body}\n    })()`;
}

const output = `/*\n${license.trim()}\n\nData source: https://github.com/smogon/damage-calc/tree/${revision}/calc/src/data\nGenerated by scripts/sync-vanilla-defaults.mjs. Do not edit by hand.\n*/\n(function () {\n    var extend = calc.extend;\n    window.calcVanillaData = {\n        revision: "${revision}",\n${dataDeclarations(species, 'species')},\n${dataDeclarations(moves, 'moves')}\n    };\n})();\n`;
const directory = fileURLToPath(new URL('../calc/data/vanilla/', import.meta.url));
await mkdir(directory, { recursive: true });
await writeFile(`${directory}base-game-data.js`, output);
console.log(`Updated vanilla defaults from smogon/damage-calc@${revision}`);
