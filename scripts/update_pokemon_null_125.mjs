// Derive 1.2.5 Lua from the existing source bundle, preserving its logging fixes.
const symbols = new Map([...read('pokeemerald.map').matchAll(/^\s*0x([a-fA-F0-9]+)\s+(\w+)(?:\s*=\s*\.)?\s*$/gm)]
    .map(match => [match[2], Number.parseInt(match[1], 16)]));
let lua = fs.readFileSync(path.join(repo, 'lua/pokemonnull1.2.lua'), 'utf8');
lua = lua.replace(/^-- AUTO-GENERATED[^\n]*/, '-- Generated by scripts/update_pokemon_null_125.mjs from pokemonnull1.2.lua and the 1.2.5 linker map.');
for (const [variable, symbol] of Object.entries({
    partyloc: 'gPlayerParty', partyCount: 'gPlayerPartyCount', enemyPartyCountLoc: 'gEnemyPartyCount',
    enemyPartyLoc: 'gEnemyParty', storageLoc: 'gPokemonStorage', speciesInfo: 'gSpeciesInfo', speciesNameTable: 'gSpeciesNames'
})) {
    assert(symbols.has(symbol), `Missing linker symbol ${symbol}`);
    const expression = new RegExp(`(local ${variable}=)0x[0-9a-fA-F]+`);
    assert(expression.test(lua), `Missing Lua address ${variable}`);
    lua = lua.replace(expression, (_match, prefix) => `${prefix}0x${symbols.get(symbol).toString(16).toUpperCase()}`);
}
for (const symbol of ['gBattlersCount', 'gBattlerPositions', 'gBattlerPartyIndexes', 'gBattleMons',
    'gTrainerBattleOpponent_A', 'gTrainerBattleOpponent_B', 'gSaveBlock2Ptr']) {
    const expression = new RegExp(`(${symbol} = [^\\n]+ or )0x[0-9a-fA-F]+`);
    assert(expression.test(lua), `Missing Lua battle address ${symbol}`);
    assert(symbols.has(symbol), `Missing linker symbol ${symbol}`);
    lua = lua.replace(expression, (_match, prefix) => `${prefix}0x${symbols.get(symbol).toString(16).toUpperCase()}`);
}
