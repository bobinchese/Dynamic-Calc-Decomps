assert.equal(git('diff', '--name-only', sourceCommit, '--', '.'), '', 'ROM sources must match the pinned commit');
const sha256 = filename => createHash('sha256').update(fs.readFileSync(filename)).digest('hex');
function loadScript(filename, binding) {
    const context = {};
    vm.runInNewContext(fs.readFileSync(filename, 'utf8'), context);
    return context[binding];
}
